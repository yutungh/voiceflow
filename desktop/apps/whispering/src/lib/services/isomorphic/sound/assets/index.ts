import type { SoundCue, SoundSet } from '$lib/constants/sounds';
import glassCancel from './glass/cancel.wav';
import glassDone from './glass/done.wav';
import glassError from './glass/error.wav';
import glassStart from './glass/start.wav';
import glassStop from './glass/stop.wav';
import minimalCancel from './minimal/cancel.wav';
import minimalDone from './minimal/done.wav';
import minimalError from './minimal/error.wav';
import minimalStart from './minimal/start.wav';
import minimalStop from './minimal/stop.wav';
import softCancel from './soft/cancel.wav';
import softDone from './soft/done.wav';
import softError from './soft/error.wav';
import softStart from './soft/start.wav';
import softStop from './soft/stop.wav';

/**
 * VoiceFlow's own sounds, generated by desktop/tools/sounds/generate.mjs
 * (original, synthesised in code; CC0 1.0). Rust embeds the same files
 * (src-tauri/src/sound.rs) to play the dictation cues without the webview.
 */
export const SOUND_URLS: Record<SoundSet, Record<SoundCue, string>> = {
	glass: {
		start: glassStart,
		stop: glassStop,
		done: glassDone,
		error: glassError,
		cancel: glassCancel,
	},
	soft: {
		start: softStart,
		stop: softStop,
		done: softDone,
		error: softError,
		cancel: softCancel,
	},
	minimal: {
		start: minimalStart,
		stop: minimalStop,
		done: minimalDone,
		error: minimalError,
		cancel: minimalCancel,
	},
};

const elements = new Map<string, HTMLAudioElement>();

/** Plays one cue through an <audio> element (the web build, and a fallback). */
export async function playWithAudioElement(
	set: SoundSet,
	cue: SoundCue,
	volume: number,
) {
	const url = SOUND_URLS[set][cue];
	let element = elements.get(url);
	if (!element) {
		element = new Audio(url);
		element.preload = 'auto';
		elements.set(url, element);
	}
	element.volume = Math.min(1, Math.max(0, volume));
	element.currentTime = 0;
	await element.play();
}
