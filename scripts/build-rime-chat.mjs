/**
 * Builds Rime's first-party chat table, vf_chat.dict.yaml (0.9.0): the
 * everyday chat words of scripts/chat-words.mjs at CHAT_BOOST times their
 * Wanxiang weight, so Rime ranks 谢谢 over 这些 the way the Java engine's
 * asset does. Run from the repo root:
 *
 *   node scripts/build-rime-chat.mjs [--out <file>] [--boost 20]
 *
 * Each word keeps the exact reading (tone marks included) and weight it has
 * in the pinned Wanxiang dictionaries (scripts/wanxiang-source.mjs, CC BY 4.0);
 * a word missing there under the listed spelling is left out, never invented.
 * Rime keeps both entries and lists the heavier one first, so this table
 * raises a word without changing anything else. MIT; the weights are derived
 * from Wanxiang data (attribution: third_party/README.md).
 */

import fs from "node:fs";
import path from "node:path";
import { CHAT_WORDS } from "./chat-words.mjs";
import { pinnedDict, readDict, WANXIANG_COMMIT } from "./wanxiang-source.mjs";

const args = process.argv.slice(2);
function option(name, fallback) {
  const at = args.indexOf(name);
  return at >= 0 ? args[at + 1] : fallback;
}

const OUTPUT = option("--out", path.join("build", "rime", "vf_chat.dict.yaml"));
/** Same factor as the Java asset's chat words; the dev benchmark decides whether it stays. */
const BOOST = Number.parseFloat(option("--boost", "20"));

const rows = [
  ...readDict(await pinnedDict("jichu")),
  ...readDict(await pinnedDict("duoyin")),
];
const wanted = new Map(CHAT_WORDS.map(([word, key]) => [`${word}\t${key}`, null]));
for (const row of rows) {
  const id = `${row.word}\t${row.syllables.join("")}`;
  if (!wanted.has(id)) {
    continue;
  }
  const best = wanted.get(id);
  if (!best || row.weight > best.weight) {
    wanted.set(id, row);
  }
}

const lines = [
  "# Rime dictionary",
  "# encoding: utf-8",
  "#",
  "# VoiceFlow's chat words (scripts/chat-words.mjs, MIT) at the readings and",
  `# ${BOOST} times the weights they have in Wanxiang (万象) by amzxyz,`,
  `# https://github.com/amzxyz/rime-wanxiang at ${WANXIANG_COMMIT},`,
  "# CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Generated by",
  "# scripts/build-rime-chat.mjs; do not edit.",
  "",
  "---",
  "name: vf_chat",
  `version: "wanxiang-${WANXIANG_COMMIT.slice(0, 8)}-x${BOOST}"`,
  "sort: by_weight",
  "...",
  "",
];
const missing = [];
let kept = 0;
for (const [id, row] of wanted) {
  if (!row) {
    missing.push(id.split("\t")[0]);
    continue;
  }
  lines.push(`${row.word}\t${row.pinyin}\t${Math.round(row.weight * BOOST)}`);
  kept++;
}

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, lines.join("\n") + "\n", "utf8");
console.log(`chat words: ${kept} of ${wanted.size} at x${BOOST}`
    + (missing.length ? `; not in the data: ${missing.join(" ")}` : ""));
console.log(`wrote ${OUTPUT}`);
